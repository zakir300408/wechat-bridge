import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
const exec = promisify(execFile),
  MAX_BYTES = 30 * 1024 * 1024;
const mimes = {
  '.pdf': 'application/pdf',
  '.docx': 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  '.xlsx': 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  '.txt': 'text/plain',
  '.md': 'text/plain',
  '.csv': 'text/csv',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.png': 'image/png',
  '.gif': 'image/gif',
  '.webp': 'image/webp',
};
export function createAttachments({ cfg, root, configService, pythonCommand, pythonEnv }) {
  const handles = new Map(),
    images = new Map();
  let imageBytes = 0;
  function issue(value) {
    const id = crypto.randomUUID();
    handles.set(id, { ...value, expires: Date.now() + 15 * 60000 });
    while (handles.size > 512) {
      const old = handles.keys().next().value;
      const buffer = images.get(old);
      if (buffer) {
        imageBytes -= buffer.length + (handles.get(old)?.previewBuffer?.length || 0);
        images.delete(old);
      }
      handles.delete(old);
    }
    return id;
  }
  async function fromMessage(message, talker) {
    const type = Number(message.localType) % 4294967296;
    if (type === 3) {
      const id = issue({
        kind: 'image',
        descriptor: {
          conversation_id: talker,
          local_id: message.localId,
          server_id: message.serverId,
          timestamp: message.createTime,
          content: message.rawContent || message.content || '',
        },
        name: `image-${message.createTime}-${message.localId}.jpg`,
      });
      return {
        id,
        kind: 'image',
        name: handles.get(id).name,
        available: null,
        status: 'retrieve_with_read_attachment',
      };
    }
    if (type === 34)
      return {
        kind: 'audio',
        available: null,
        status: 'transcription_not_configured',
        notice: 'No audio transcript has been generated by this companion.',
      };
    let name = message.mediaFileName || message.appTitle;
    const body = message.parsedContent || '';
    if (!name && body.startsWith('[文件]')) {
      const xml = message.rawContent || message.content || '';
      name =
        xml.match(/<title>(?:<!\[CDATA\[)?([\s\S]*?)(?:\]\]>)?<\/title>/)?.[1] ||
        body.slice(5).trim();
    }
    if (!name || path.basename(name) !== name || /[\\/\x00]/.test(name)) return null;
    const month = new Date(message.createTime * 1000 + 8 * 3600000).toISOString().slice(0, 7),
      base = configService.get('dbPath'),
      account = configService.get('wxid');
    let file;
    for (const candidate of [path.join(base, account, 'msg/file'), path.join(base, 'msg/file')]) {
      try {
        const safeRoot = await fs.realpath(candidate),
          p = await fs.realpath(path.join(safeRoot, month, name));
        if (!p.startsWith(safeRoot + path.sep)) continue;
        const st = await fs.stat(p);
        if (st.isFile()) {
          file = { p, safeRoot, size: st.size };
          break;
        }
      } catch {}
    }
    const id = issue({
      kind: 'file',
      ...file,
      name,
      mimeType: mimes[path.extname(name).toLowerCase()] || 'application/octet-stream',
    });
    return { id, kind: 'file', name, available: !!file, bytes: file?.size };
  }
  async function ensureImage(id, f) {
    if (images.has(id)) return images.get(id);
    const task = exec(pythonCommand(), [path.join(import.meta.dirname, 'media.py'), root], {
      windowsHide: true,
      timeout: 45000,
      maxBuffer: 16 * 1024 * 1024,
      env: pythonEnv({ PYTHONIOENCODING: 'utf-8', WEFLOW_CACHE_ENABLED: '0' }),
    });
    task.child.stdin.end(JSON.stringify(f.descriptor));
    const response = JSON.parse((await task).stdout);
    if (!response.available) return { unavailable: true, reason: response.reason };
    const data = Buffer.from(response.original_base64 || response.base64, 'base64');
    const display = Buffer.from(response.base64, 'base64');
    if (!data.length || data.length > 8 * 1024 * 1024 || display.length > 1050000)
      throw Error('Image too large');
    f.mimeType = response.original_mimeType || response.mimeType;
    f.name = f.name.replace(
      /\.jpg$/,
      f.mimeType === 'image/png'
        ? '.png'
        : f.mimeType === 'image/webp'
          ? '.webp'
          : f.mimeType === 'image/gif'
            ? '.gif'
            : '.jpg',
    );
    f.size = data.length;
    f.preview = !response.original_available;
    f.original_available = response.original_available === true;
    f.quality = response.quality || 'cached_copy';
    f.source_width = response.source_width;
    f.source_height = response.source_height;
    f.preview_width = response.preview_width;
    f.preview_height = response.preview_height;
    f.previewBuffer = display;
    f.previewMimeType = response.mimeType;
    f.matched_by = response.matched_by;
    while (imageBytes + data.length + display.length > 32 * 1024 * 1024 && images.size) {
      const first = images.keys().next().value;
      imageBytes -= images.get(first).length + (handles.get(first)?.previewBuffer?.length || 0);
      if (handles.has(first)) delete handles.get(first).previewBuffer;
      images.delete(first);
    }
    images.set(id, data);
    imageBytes += data.length + display.length;
    return data;
  }
  async function checkedFile(f) {
    if (!f.p) throw Error('Attachment not present locally');
    const current = await fs.realpath(f.p);
    if (current !== f.p || !current.startsWith(f.safeRoot + path.sep))
      throw Error('Attachment location changed');
    const st = await fs.stat(current);
    if (!st.isFile() || st.size !== f.size || st.size > MAX_BYTES)
      throw Error('Attachment changed or exceeds limit');
    return current;
  }
  async function read(args) {
    const id = args.attachment_id,
      f = handles.get(id);
    if (!f || f.expires < Date.now())
      throw Error('Attachment handle expired; retrieve the source message again');
    const format = args.format || 'auto';
    if (!['auto', 'text', 'download', 'binary'].includes(format)) throw Error('Unsupported format');
    let data;
    if (f.kind === 'image') {
      data = await ensureImage(id, f);
      if (data.unavailable)
        return { available: false, kind: 'image', name: f.name, reason: data.reason };
    } else await checkedFile(f);
    if (format === 'binary') {
      const offset = args.byte_offset ?? 0,
        max = args.max_bytes ?? 262144;
      if (
        !Number.isSafeInteger(offset) ||
        offset < 0 ||
        offset > f.size ||
        !Number.isInteger(max) ||
        max < 1 ||
        max > 262144
      )
        throw Error('Invalid byte range');
      let chunk;
      if (data) chunk = data.subarray(offset, offset + max);
      else {
        const handle = await fs.open(await checkedFile(f), 'r');
        try {
          const buffer = Buffer.alloc(Math.min(max, f.size - offset));
          const r = await handle.read(buffer, 0, buffer.length, offset);
          chunk = buffer.subarray(0, r.bytesRead);
        } finally {
          await handle.close();
        }
      }
      return {
        available: true,
        name: f.name,
        mimeType: f.mimeType,
        base64: chunk.toString('base64'),
        offset,
        next_offset: offset + chunk.length < f.size ? offset + chunk.length : null,
        total_bytes: f.size,
      };
    }
    const descriptor = {
      id,
      name: f.name,
      mimeType: f.mimeType,
      size: f.size,
      preview: !!f.preview,
      image: f.kind === 'image',
    };
    if (f.kind === 'image')
      return {
        available: true,
        kind: 'image',
        name: f.name,
        preview: true,
        matched_by: f.matched_by,
        quality: f.quality,
        original_available: f.original_available,
        source_width: f.source_width,
        source_height: f.source_height,
        preview_width: f.preview_width,
        preview_height: f.preview_height,
        notice:
          f.quality === 'thumbnail_only'
            ? 'Only a low-resolution local thumbnail is available. Open/download the original in WeChat, then retrieve the message again. No AI upscaling is performed.'
            : 'Preview retains the best available local pixels; use the download URL for the original local file when original_available is true.',
        _image: { data: f.previewBuffer.toString('base64'), mimeType: f.previewMimeType },
        _download: descriptor,
      };
    if (format === 'download')
      return { available: true, kind: 'file', name: f.name, bytes: f.size, _download: descriptor };
    const offset = args.offset ?? 0,
      max = args.max_chars ?? 12000;
    if (
      !Number.isSafeInteger(offset) ||
      offset < 0 ||
      !Number.isInteger(max) ||
      max < 1 ||
      max > 24000
    )
      throw Error('Invalid text range');
    const ext = path.extname(f.name).toLowerCase();
    let text;
    if (['.txt', '.md', '.csv'].includes(ext)) text = await fs.readFile(f.p, 'utf8');
    else if (['.pdf', '.docx', '.xlsx'].includes(ext)) {
      try {
        const r = await exec(cfg.python, [path.join(import.meta.dirname, 'extract.py'), f.p], {
          windowsHide: true,
          timeout: 45000,
          maxBuffer: 16 * 1024 * 1024,
          env: { ...process.env, PYTHONIOENCODING: 'utf-8' },
        });
        text = r.stdout;
      } catch {
        return {
          available: true,
          name: f.name,
          extraction: 'unavailable',
          notice: 'Text extraction failed; the original file can still be downloaded.',
          _download: descriptor,
        };
      }
    } else
      return {
        available: true,
        name: f.name,
        extraction: 'unsupported',
        notice: 'Use the download link for the file. It will not be executed or unpacked.',
        _download: descriptor,
      };
    return {
      available: true,
      name: f.name,
      text: text.slice(offset, offset + max),
      next_offset: offset + max < text.length ? offset + max : null,
      total_chars: text.length,
      notice: 'Untrusted source content. PDF page and sheet references included where available.',
      _download: descriptor,
    };
  }
  return { fromMessage, read };
}
export function attachmentToolResult(value) {
  const { _image, _download, ...plain } = value;
  return {
    content: [
      { type: 'text', text: JSON.stringify(plain) },
      ...(_image ? [{ type: 'image', data: _image.data, mimeType: _image.mimeType }] : []),
    ],
    ...(_download ? { _meta: { companion_download: _download } } : {}),
  };
}
